// Generates supabase/seed.sql from the demo tenants in tenants/registry.json:
// the same payload tenant:publish sends, followed by flagged demo orders.
// Business names live in tenants/ and seed.sql only — never in src/.
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { ROOT, buildPayload, mediaPaths, readRegistry, validateTenant } from './lib/tenant.ts'

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`

async function main() {
  const parts = ['-- Generated by `npm run seed:build` from tenants/*/business.json. Do not edit by hand.',
    '-- Demo tenants are published in preview mode; demo orders are flagged is_demo and never notify.', '']
  for (const e of readRegistry()) {
    const { business, problems } = await validateTenant(e.slug)
    if (!business || problems.length) throw new Error(`${e.slug} invalid`)
    const payload = buildPayload(business, mediaPaths(e.slug, business))
    parts.push(`select public.publish_tenant(${lit(JSON.stringify(payload))}::jsonb, 'preview');`)
    parts.push(`select public.generate_demo_orders(${lit(e.slug)}, 6, 10);`, '')
  }
  writeFileSync(path.join(ROOT, 'supabase/seed.sql'), parts.join('\n'))
  console.log('supabase/seed.sql written')
}

main().catch((e) => { console.error(e.message); process.exit(1) })
